const { chromium } = require(process.env.UI_PLAYWRIGHT_PATH || 'playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const root = path.resolve(__dirname, '../..');
const output = process.env.UI_QA_OUTPUT || path.join(os.tmpdir(), 'food-roll-overlay-qa');
const food = { ...JSON.parse(fs.readFileSync(path.join(root, 'backend/src/data/foods.json'), 'utf8'))[0], _id: '000000000000000000000001', imageUrl: '' };
const checks = [];
const check = (name, value = true) => { assert.ok(value, name); checks.push(name); console.log('PASS', name); };
let browser;
(async () => {
  fs.mkdirSync(output, { recursive: true });
  browser = await chromium.launch({ headless: true, ...(process.env.UI_BROWSER_EXECUTABLE ? { executablePath: process.env.UI_BROWSER_EXECUTABLE } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let mode = 'fast', release, calls = 0;
  await page.route(url => url.pathname.startsWith('/api/'), async route => {
    assert.equal(new URL(route.request().url()).pathname, '/api/foods/random');
    assert.equal(new URL(route.request().url()).search, '?maxPrice=45001');
    assert.equal(route.request().method(), 'GET');
    calls++;
    const state = mode;
    if (state === 'slow') await new Promise(resolve => { release = resolve; });
    if (state === 'network') return route.abort('failed');
    await route.fulfill({ status: state === 'error' ? 500 : state === 'empty' ? 404 : 200, contentType: 'application/json', body: JSON.stringify(state === 'error' ? { error: { code: 'INTERNAL_SERVER_ERROR', message: 'Lỗi thử nghiệm.' } } : state === 'empty' ? { error: { code: 'FOOD_NOT_FOUND', message: 'Không có món.' } } : { data: food }) });
  });
  const overlay = () => page.locator('dialog.roll-overlay');
  const card = () => overlay().locator('.food-card');
  const start = async () => {
    if (await page.getByRole('button', { name: 'Chọn ngân sách và roll', exact: true }).isVisible()) await page.getByRole('button', { name: 'Chọn ngân sách và roll', exact: true }).click();
    else await page.getByRole('button', { name: 'Đổi ngân sách', exact: true }).first().click();
    await page.getByLabel('Mức chi tối đa (đ)', { exact: true }).fill('45001');
    await page.getByRole('button', { name: 'Gọi sao băng', exact: true }).click();
    await overlay().waitFor();
  };
  const close = async () => { await overlay().getByRole('button', { name: 'Đóng', exact: true }).click(); await overlay().waitFor({ state: 'detached' }); };
  const homeAndRoll = async () => {
    await page.getByRole('navigation').getByRole('button', { name: 'Bản đồ', exact: true }).click();
    await page.getByRole('navigation').getByRole('button', { name: 'Food Roll', exact: true }).click();
  };
  const screenshot = async name => page.screenshot({ path: path.join(output, `${name}.png`) });
  await page.goto(process.env.UI_PREVIEW_URL || 'http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' });
  await page.getByRole('navigation').getByRole('button', { name: 'Food Roll', exact: true }).click();
  await start();
  const box = await overlay().boundingBox();
  check('Desktop overlay covers at least 90% of both dimensions', box.width >= 1440 * .9 && box.height >= 1000 * .9);
  check('Skip is visible and labeled', await overlay().getByRole('button', { name: 'Skip', exact: true }).isVisible());
  await page.waitForTimeout(450);
  check('Fast API does not reveal before ceremony completes', await card().count() === 0);
  await screenshot('desktop-flight');
  const beforeSkip = calls, skippedAt = Date.now();
  await overlay().getByRole('button', { name: 'Skip', exact: true }).click();
  await card().waitFor();
  check('Skip reveals available real food immediately', Date.now() - skippedAt < 700);
  check('Skip makes no additional API request', calls === beforeSkip && calls === 1);
  check('FoodCard shows the actual response', await card().locator('.food-card__name').textContent() === food.name);
  check('Overlay stays open after reveal', await overlay().isVisible());
  check('Live region announces actual result', (await overlay().locator('[role=status]').textContent()).includes(food.name));
  await screenshot('desktop-result');
  await close();
  check('Closing restores the result to the page', await page.locator('.roll-stage .food-card').isVisible());

  mode = 'slow';
  await page.getByRole('button', { name: 'Roll lại', exact: true }).click();
  await overlay().waitFor();
  await page.waitForFunction(() => document.querySelector('.summon-scene'));
  const slowCalls = calls;
  await overlay().getByRole('button', { name: 'Skip', exact: true }).click();
  await overlay().getByRole('heading', { name: 'Đang tìm món', exact: true }).waitFor();
  check('Skip before response waits honestly without a fake card', await card().count() === 0);
  check('Skip removes the moving sequence', await overlay().locator('.summon-traveler').count() === 0);
  await overlay().getByRole('button', { name: 'Skip', exact: true }).click();
  check('Repeated Skip keeps the same single pending request', calls === slowCalls);
  for (let i = 0; i < 5; i++) { await page.keyboard.press('Tab'); assert.ok(await overlay().evaluate(el => el.contains(document.activeElement))); }
  check('Keyboard focus stays inside overlay');
  release(); await card().waitFor();
  check('Skipped slow request reveals when the response arrives');

  mode = 'slow';
  await overlay().getByRole('button', { name: 'Roll lại', exact: true }).click();
  await overlay().getByRole('heading', { name: 'Đang tìm món', exact: true }).waitFor();
  check('Natural sequence ends in static loading on slow API', await overlay().locator('.summon-traveler').count() === 0 && await card().count() === 0);
  await page.keyboard.press('Escape');
  await overlay().waitFor({ state: 'detached' });
  check('Escape closes pending overlay', await overlay().count() === 0);
  check('Roll remains locked while the closed request is pending', await page.getByRole('button', { name: 'Đổi ngân sách', exact: true }).isDisabled());
  release(); await page.locator('.roll-stage .food-card').waitFor();
  check('Closing cannot cancel or duplicate the actual result request');

  mode = 'error';
  await page.getByRole('button', { name: 'Roll lại', exact: true }).click();
  await overlay().getByRole('heading', { name: 'Chưa thể chọn món', exact: true }).waitFor();
  check('Server error stays inside overlay with retry and close', await overlay().getByRole('button', { name: 'Thử lại', exact: true }).isVisible() && await card().count() === 0);
  mode = 'empty';
  await overlay().getByRole('button', { name: 'Thử lại', exact: true }).click();
  await overlay().getByRole('heading', { name: 'Chưa có món trong ngân sách', exact: true }).waitFor();
  check('Empty response stays inside overlay without a fabricated result', await card().count() === 0);
  mode = 'network';
  await overlay().getByRole('button', { name: 'Thử lại', exact: true }).click();
  await overlay().getByRole('heading', { name: 'Chưa thể chọn món', exact: true }).waitFor();
  check('Network failure preserves adapter error message', (await overlay().getByRole('alert').textContent()).includes('Không kết nối được máy chủ'));
  mode = 'fast';
  const naturalStart = Date.now();
  await overlay().getByRole('button', { name: 'Thử lại', exact: true }).click();
  await card().waitFor();
  check('Retry uses the new Motion sequence and completes normally', Date.now() - naturalStart > 2000);
  await close();

  await page.emulateMedia({ reducedMotion: 'reduce' });
  const reducedStart = Date.now();
  await page.getByRole('button', { name: 'Roll lại', exact: true }).click();
  await card().waitFor();
  check('Reduced motion bypasses the ritual wait', Date.now() - reducedStart < 1000);
  await close();
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.getByRole('button', { name: 'Roll lại', exact: true }).click();
  await overlay().locator('.summon-traveler').waitFor();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await card().waitFor();
  check('Enabling reduced motion mid-sequence reveals correctly');
  await close();

  for (const width of [375, 768, 1024, 1440]) {
    await homeAndRoll();
    await page.setViewportSize({ width, height: 900 });
    mode = 'slow';
    await start();
    const size = await overlay().boundingBox();
    check(`Overlay fits ${width}px viewport`, size.width <= width + 1 && size.height <= 901 && await overlay().evaluate(el => el.scrollWidth <= el.clientWidth));
    if (width === 375) check('Phone overlay occupies full screen', Math.abs(size.width - width) < 2 && Math.abs(size.height - 900) < 2);
    await overlay().getByRole('button', { name: 'Skip', exact: true }).click();
    await screenshot(`waiting-${width}`);
    release(); await card().waitFor();
    check(`Result reflows at ${width}px`, await overlay().locator('.roll-overlay__body').evaluate(el => el.scrollWidth <= el.clientWidth));
    await screenshot(`result-${width}`); await close();
  }
  check('No browser runtime errors', errors.length === 0);
  fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ checks: checks.length, passed: checks, requests: calls, pageErrors: errors, backend: 'HTTP intercepted; no Atlas' }, null, 2));
  console.log(JSON.stringify({ checks: checks.length, requests: calls, errors }, null, 2));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
