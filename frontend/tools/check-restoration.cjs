const { chromium } = require(process.env.UI_PLAYWRIGHT_PATH || 'playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { rankFoods, decideGroup } = require('../../backend/src/services/decision');
const foods = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../../backend/src/data/foods.json'), 'utf8')).map((food, index) => ({ ...food, _id: (index + 1).toString(16).padStart(24, '0'), imageUrl: '' }));
let browser;
const checks = [];
const check = (name, value = true) => { assert.ok(value, name); checks.push(name); console.log('PASS', name); };
(async () => {
  browser = await chromium.launch({ headless: true, ...(process.env.UI_BROWSER_EXECUTABLE ? { executablePath: process.env.UI_BROWSER_EXECUTABLE } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let groupCalls = 0, recommendationCalls = 0, rollCalls = 0, hold = false, holdCatalog = false, release, catalogError = false;
  await page.route(url => url.pathname.startsWith('/api/'), async route => {
    const url = new URL(route.request().url());
    const input = route.request().method() === 'POST' ? route.request().postDataJSON() : null;
    let data;
    if (url.pathname === '/api/foods') {
      if (catalogError) return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'UNAVAILABLE', message: 'Máy chủ tạm thời không khả dụng.' } }) });
      data = foods;
    } else if (url.pathname === '/api/recommendations') { recommendationCalls++; data = rankFoods(foods, input); }
    else if (url.pathname === '/api/group-decision') { groupCalls++; data = decideGroup(input.foodIds.map(id => foods.find(food => food._id === id)), input); }
    else if (url.pathname === '/api/foods/random') { rollCalls++; data = foods[0]; }
    else data = foods.find(food => food._id === url.pathname.split('/').at(-1));
    if ((hold && input) || (holdCatalog && url.pathname === '/api/foods')) await new Promise(resolve => { release = resolve; });
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ data }) });
  });
  const nav = async name => page.getByRole('navigation', { name: 'Chế độ chọn món' }).getByRole('button', { name, exact: true }).click();
  const catalog = async () => page.locator('.codex-grid .food-card').first().waitFor();
  const form = async () => page.locator(`[data-route="${new URL(page.url()).searchParams.get('page')}"] .decision-submit`).waitFor();
  await page.goto(process.env.UI_PREVIEW_URL || 'http://127.0.0.1:5173');
  await nav('Khám phá'); await catalog();
  await page.getByLabel('Tìm món', { exact: true }).fill('Cơm');
  await page.getByLabel('Loại món', { exact: true }).selectOption('rice');
  await page.getByLabel('Sắp xếp').selectOption('price-desc');
  check('Catalog filters are represented in URL', new URL(page.url()).searchParams.get('q') === 'Cơm' && new URL(page.url()).searchParams.get('category') === 'rice');
  await page.locator('.codex-grid button').first().click();
  await page.locator('.food-detail__description').waitFor();
  const detailId = new URL(page.url()).searchParams.get('food');
  await page.reload(); await page.locator('.food-detail__description').waitFor();
  check('Reload restores the detail ID and refetches actual detail', new URL(page.url()).searchParams.get('food') === detailId);
  await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({ state: 'detached' });
  check('Catalog query and sort survive detail refresh', await page.getByLabel('Tìm món', { exact: true }).inputValue() === 'Cơm' && await page.getByLabel('Sắp xếp').inputValue() === 'price-desc');
  await nav('Gợi ý'); await form();
  await page.getByLabel('Ngân sách mỗi người (đ)').fill('73123');
  await page.getByLabel('Mì & bún', { exact: true }).check();
  await page.getByLabel('Độ cay', { exact: true }).selectOption('1');
  await page.getByLabel('Độ no', { exact: true }).selectOption('3');
  await nav('Nhóm'); await form();
  await page.locator('.candidate-list input').nth(0).check(); await page.locator('.candidate-list input').nth(2).check();
  await page.getByLabel('Ngân sách mỗi người (đ)').fill('80000');
  await page.getByLabel('Tránh món cay nhiều').check();
  await page.getByRole('button', { name: 'Lọc món cho nhóm', exact: true }).click();
  await page.locator('.eliminated-section').waitFor();
  await page.getByRole('button', { name: 'Chọn ngẫu nhiên trong vòng cuối', exact: true }).click();
  const winner = await page.locator('.group-winner h3').textContent();
  await page.reload(); await page.locator('.group-winner h3').waitFor();
  check('Group draft and real result restore without resubmission', await page.locator('.candidate-list input:checked').count() === 2 && groupCalls === 1);
  check('Actual chosen finalist is restored', await page.locator('.group-winner h3').textContent() === winner);
  await nav('Gợi ý'); await form();
  check('Oracle form is preserved across navigation', await page.getByLabel('Ngân sách mỗi người (đ)').inputValue() === '73123' && await page.getByLabel('Độ no', { exact: true }).inputValue() === '3');
  await page.getByRole('button', { name: 'Gợi ý cho tôi', exact: true }).click(); await page.locator('.recommendation-list').waitFor();
  const names = await page.locator('.recommendation-list .food-card__name').allTextContents();
  await page.reload(); await page.locator('.recommendation-list').waitFor();
  assert.deepEqual(await page.locator('.recommendation-list .food-card__name').allTextContents(), names);
  check('Genuine recommendation result restores without a POST replay', recommendationCalls === 1);
  await page.getByLabel('Độ cay', { exact: true }).selectOption('0');
  check('Editing criteria invalidates restored result', await page.locator('.recommendation-list').count() === 0);
  hold = true;
  await page.getByRole('button', { name: 'Gợi ý cho tôi', exact: true }).click();
  await page.waitForTimeout(120);
  await page.reload(); await form();
  check('Reload during a request restores an editable draft, never loading', !(await page.locator('.decision-submit').isDisabled()) && await page.locator('.recommendation-list').count() === 0);
  hold = false; release();
  await nav('Khám phá'); await catalog();
  check('Catalog filters return after visiting other modes', await page.getByLabel('Tìm món', { exact: true }).inputValue() === 'Cơm');
  await page.goBack(); await form(); check('Browser Back restores the prior mode', new URL(page.url()).searchParams.get('page') === 'oracle');
  await page.goForward(); await catalog(); check('Browser Forward restores catalog', new URL(page.url()).searchParams.get('page') === 'codex');
  await nav('Food Roll');
  await page.getByRole('button', { name: 'Chọn ngân sách và roll', exact: true }).click();
  await page.getByLabel('Mức chi tối đa (đ)', { exact: true }).fill('45001');
  await page.getByRole('button', { name: 'Gọi sao băng', exact: true }).click();
  await page.getByRole('button', { name: 'Skip', exact: true }).click();
  await page.locator('.roll-overlay .food-card').waitFor();
  await page.reload(); await page.locator('.roll-stage .food-card').waitFor();
  check('Roll refresh restores actual food and budget without a new request', rollCalls === 1 && (await page.locator('.roll-budget__amount').textContent()).includes('45.001'));
  check('Roll overlay/loading are not restored after refresh', await page.locator('.roll-overlay').count() === 0);
  await page.evaluate(() => { sessionStorage.setItem('food-decision:v2:roll:food', '{bad'); sessionStorage.setItem('food-decision:v2:oracle:budget', JSON.stringify({ version: 2, savedAt: Date.now(), value: { bad: true } })); sessionStorage.setItem('food-decision:v2:oracle:spicy', JSON.stringify({ version: 1, savedAt: Date.now(), value: 2 })); sessionStorage.setItem('food-decision:v2:oracle:fullness', JSON.stringify({ version: 2, savedAt: Date.now() - 86400001, value: 3 })); });
  await page.reload(); await page.getByRole('button', { name: 'Chọn ngân sách và roll', exact: true }).waitFor();
  check('Corrupt stored result falls back to safe idle');
  await nav('Gợi ý'); await form();
  check('Wrong-type draft is rejected', await page.getByLabel('Ngân sách mỗi người (đ)').inputValue() === '50000');
  check('Older storage version is rejected', await page.getByLabel('Độ cay', { exact: true }).inputValue() === '0');
  check('Expired session value is rejected', await page.getByLabel('Độ no', { exact: true }).inputValue() === '2');
  await page.addInitScript(() => Object.defineProperty(window, 'sessionStorage', { get() { throw new DOMException('Storage disabled', 'SecurityError'); } }));
  await page.reload(); await form();
  await page.getByLabel('Ngân sách mỗi người (đ)').fill('60000');
  check('Blocked storage does not prevent editing', await page.getByLabel('Ngân sách mỗi người (đ)').inputValue() === '60000');
  catalogError = true; await nav('Khám phá'); await page.getByRole('heading', { name: 'Chưa tải được thực đơn', exact: true }).waitFor();
  check('Real server failure stays an error, not cached fake success', await page.locator('.codex-grid').count() === 0);
  catalogError = false; await page.getByRole('button', { name: 'Thử lại', exact: true }).click(); await catalog(); check('Catalog retry recovers');
  await nav('Bản đồ'); await page.locator('.destination').first().waitFor();
  await page.clock.install(); holdCatalog = true;
  await nav('Khám phá'); await page.locator('.loading-shell').waitFor();
  await page.clock.fastForward(15100);
  await page.getByRole('heading', { name: 'Chưa tải được thực đơn', exact: true }).waitFor();
  check('Timeout has a specific recovery message', (await page.getByRole('alert').textContent()).includes('phản hồi quá lâu'));
  holdCatalog = false; release();
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click(); await catalog();
  check('Timeout retry recovers normally');
  check('No runtime errors during recovery cases', errors.length === 0);
  console.log(JSON.stringify({ checks: checks.length, groupCalls, recommendationCalls, rollCalls, errors }, null, 2));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => browser?.close());
